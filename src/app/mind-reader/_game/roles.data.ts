/**
 * The Mind Reader deck.
 *
 * Every line is something player A could say out loud to player B, which is
 * why they all start with "I am". Grouping them by category is what lets a
 * pair pick the flavour of game they want without me hand-tagging anything
 * twice: ids are built from the category and the position in its list.
 */

export type CategoryId =
  | "protector"
  | "threat"
  | "secret"
  | "history"
  | "fantasy"
  | "everyday";

export type Category = { id: CategoryId; label: string; blurb: string };

export type Role = { id: string; text: string; category: CategoryId };

